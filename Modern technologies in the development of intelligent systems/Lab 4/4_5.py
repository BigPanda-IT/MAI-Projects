    axes[i].set_title(f'Распределение: {title}', fontsize=12, fontweight='bold')
    axes[i].set_xlabel('Значение', fontsize=10)
    axes[i].set_ylabel('Плотность', fontsize=10)
    axes[i].legend(loc='upper right')
    axes[i].grid(True, alpha=0.3)

