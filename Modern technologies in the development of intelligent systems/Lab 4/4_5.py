# Задание 5. Визуализация результатов обработки
# Полный готовый код

import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.pipeline import Pipeline
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.ensemble import IsolationForest
from sklearn.base import BaseEstimator, TransformerMixin

# Установка стиля для графиков
plt.style.use('seaborn-v0_8-darkgrid')
sns.set_palette("husl")
plt.rcParams['figure.figsize'] = (12, 8)
plt.rcParams['font.size'] = 12

# Загрузка данных
url = "https://raw.githubusercontent.com/datasciencedojo/datasets/master/titanic.csv"
df = pd.read_csv(url)

# Очистка данных (базовая)
df['Age'] = df['Age'].fillna(df['Age'].median())
df['Fare'] = df['Fare'].fillna(df['Fare'].median())
df['Embarked'] = df['Embarked'].fillna(df['Embarked'].mode()[0])

print("Исходные данные загружены")
print(f"Размер данных: {df.shape}")
print(f"Колонки: {df.columns.tolist()}")

# ========== 1. ОПРЕДЕЛЕНИЕ КЛЮЧЕВЫХ ПРИЗНАКОВ ==========
key_features = ['Age', 'Fare', 'SibSp', 'Parch']
categorical_features = ['Sex', 'Pclass']

# ========== 2. ПРИМЕНЕНИЕ ОБРАБОТКИ ДЛЯ ВИЗУАЛИЗАЦИИ ==========

# Создаём обработанную версию данных
df_processed = df.copy()

# Масштабирование числовых признаков
scaler = StandardScaler()
df_processed[key_features] = scaler.fit_transform(df_processed[key_features])

# One-hot кодирование
df_processed = pd.get_dummies(df_processed, columns=['Sex'], prefix='Sex', drop_first=True)
df_processed['Pclass'] = df_processed['Pclass'].astype('category')

print("\nДанные после обработки:")
print(f"Размер: {df_processed.shape}")

# ========== 3. ТЕПЛОВАЯ КАРТА КОРРЕЛЯЦИИ ДО ОБРАБОТКИ ==========
print("\n" + "="*60)
print("1. ПОСТРОЕНИЕ ТЕПЛОВЫХ КАРТ КОРРЕЛЯЦИИ")
print("="*60)

# Выбираем числовые признаки для корреляции
numeric_cols = ['Age', 'Fare', 'SibSp', 'Parch', 'Survived']
if 'Pclass' in df.columns:
    numeric_cols.append('Pclass')

df_numeric_before = df[numeric_cols].copy()
corr_before = df_numeric_before.corr()

fig, axes = plt.subplots(1, 2, figsize=(16, 7))

# Heatmap ДО обработки
mask = np.triu(np.ones_like(corr_before, dtype=bool))
sns.heatmap(corr_before,
            annot=True,
            fmt='.2f',
            cmap='coolwarm',
            center=0,
            square=True,
            linewidths=0.5,
            cbar_kws={"shrink": 0.8},
            mask=mask,
            ax=axes[0])
axes[0].set_title('Корреляционная матрица\nДО обработки данных', fontsize=14, fontweight='bold')
axes[0].set_xlabel('Признаки', fontsize=12)
axes[0].set_ylabel('Признаки', fontsize=12)

# Heatmap ПОСЛЕ обработки (после масштабирования и кодирования)
# Для после обработки используем те же признаки + закодированный Sex
processed_cols = ['Age', 'Fare', 'SibSp', 'Parch', 'Survived', 'Sex_male']
df_processed_numeric = df_processed[processed_cols].copy()
df_processed_numeric['Pclass'] = df['Pclass']  # добавляем Pclass как числовой

corr_after = df_processed_numeric.corr()

sns.heatmap(corr_after,
            annot=True,
            fmt='.2f',
            cmap='coolwarm',
            center=0,
            square=True,
            linewidths=0.5,
            cbar_kws={"shrink": 0.8},
            mask=np.triu(np.ones_like(corr_after, dtype=bool)),
            ax=axes[1])
axes[1].set_title('Корреляционная матрица\nПОСЛЕ обработки данных', fontsize=14, fontweight='bold')
axes[1].set_xlabel('Признаки', fontsize=12)
axes[1].set_ylabel('Признаки', fontsize=12)

plt.tight_layout()
plt.savefig('correlation_heatmap_comparison.png', dpi=150, bbox_inches='tight')
plt.show()
print("✅ График сохранён: correlation_heatmap_comparison.png")

